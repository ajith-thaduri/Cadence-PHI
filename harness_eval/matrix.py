"""Entity responsibility matrix + HIPAA Safe Harbor coverage, generated from the catalog and the
recognizer `emits` declarations (never hand-kept).

  python -m harness_eval.matrix [--env base] [--evidence results/.../summary.json]

Writes configs/phi/generated/entity_responsibility.yaml (machine-readable) and
docs/entity_responsibility_matrix.md. Flags entities with no enabled recognizer and enabled entities
that depend on a single recognizer type (single point of failure).
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any, Optional

import yaml

from harness.label_mapping import LabelMapping
from harness.paths import ROOT
from harness.phi.catalog import Catalog
from harness.phi.config import HarnessConfig

TYPES = ["deterministic_rule", "contextual_rule", "registry", "contextual_ml", "presidio_predefined"]



def _rel(p) -> str:
    from harness.paths import ROOT
    try:
        return str(Path(p).resolve().relative_to(ROOT))
    except (ValueError, TypeError):
        return str(p)

def _rec_type(spec: dict) -> str:
    if spec.get("type") in ("pattern", "labelled") or "family" in spec:
        return "deterministic_rule"
    if spec.get("contextual"):
        return "contextual_rule"
    if "kinds" in spec:
        return "registry"
    return "presidio_predefined"


def build(cfg: HarnessConfig, evidence: Optional[dict[str, Any]] = None) -> dict[str, Any]:
    cat = Catalog(cfg)
    rows: dict[str, list[dict[str, Any]]] = {e: [] for e in cat.ids}
    kind_entities = (cfg.raw.get("registry") or {}).get("kind_entities") or {}
    for rid, spec in cfg.raw["recognizers"].items():
        t = _rec_type(spec)
        if spec.get("type") == "pattern":
            emits = [spec["entity"]]
        elif spec.get("type") == "labelled":
            emits = sorted(spec["labels"])
        elif "kinds" in spec:
            emits = sorted({e for k in spec["kinds"] for e in kind_entities.get(k, [])})
        elif "entity_map" in spec:
            emits = list(spec["entity_map"].values())
        else:
            emits = spec.get("emits") or []
        for e in emits:
            if e in rows:
                rows[e].append({"recognizer": rid, "type": t, "enabled": cfg.recognizer_enabled(rid)})
    for m, spec in cfg.raw["models"].items():
        try:
            mp = LabelMapping.load(m)
            ents = sorted({mp.to_canonical(n) for n in mp.native_labels} - {"UNMAPPED"})
        except Exception:  # noqa: BLE001
            ents = []
        for e in ents:
            if e in rows:
                rows[e].append({"recognizer": f"model_{m}", "type": "contextual_ml", "enabled": bool(spec.get("enabled")),
                                "mode": spec.get("mode", "production")})
    out: dict[str, Any] = {"generated_from": _rel((cfg.raw.get("_source") or {}).get("root", cfg.path)), "config_sha256": cfg.sha256(),
                           "catalog_version": cat.version, "entities": {}, "safe_harbor": cat.safe_harbor_coverage()}
    for e, rs in rows.items():
        info = cat[e]
        enabled_types = sorted({r["type"] for r in rs if r["enabled"]})
        out["entities"][e] = {"enabled": info.enabled, "risk_tier": info.risk_tier, "category": info.category,
                              "hipaa_safe_harbor": list(info.hipaa_safe_harbor), "description": info.description,
                              "recognizers": rs, "enabled_sources": enabled_types,
                              "no_enabled_recognizer": info.enabled and not enabled_types,
                              "single_source": info.enabled and len(enabled_types) == 1}
        if evidence:
            for ds, d in evidence.get("datasets", {}).items():
                att = (d.get("breakdown") or {}).get("attribution", {}).get(e)
                if att:
                    out["entities"][e].setdefault("measured_outcomes", {})[ds] = att
    return out


def to_markdown(m: dict[str, Any]) -> str:
    L = ["# Entity responsibility matrix", "",
         f"Generated by `python -m harness_eval.matrix` from `{m['generated_from']}` (config sha {m['config_sha256']}, "
         f"catalog {m['catalog_version']}). Do not edit by hand; machine-readable copy: "
         "`configs/phi/generated/entity_responsibility.yaml`.", "",
         "**bold** = enabled · plain = available but disabled · ⚠ = enabled entity with no enabled recognizer · "
         "◐ = enabled entity relying on a single recognizer type (single point of failure)", "",
         "| entity | tier | Safe Harbor | deterministic rules | contextual rules | registry | contextual ML | Presidio predefined |",
         "|---|---|---|---|---|---|---|---|"]
    for e, d in m["entities"].items():
        cell = lambda t: ", ".join((f"**{r['recognizer']}**" if r["enabled"] else r["recognizer"])
                                   for r in d["recognizers"] if r["type"] == t) or "–"
        flag = " ⚠" if d["no_enabled_recognizer"] else (" ◐" if d["single_source"] else "")
        name = e if d["enabled"] else f"{e} (disabled)"
        L.append(f"| {name}{flag} | {d['risk_tier']} | {', '.join(d['hipaa_safe_harbor']) or '–'} | {cell('deterministic_rule')} | "
                 f"{cell('contextual_rule')} | {cell('registry')} | {cell('contextual_ml')} | {cell('presidio_predefined')} |")
    L += ["", "## HIPAA Safe Harbor coverage", "", "| Safe Harbor identifier | catalog entities | enabled | status |",
          "|---|---|---|---|"]
    for sh, d in m["safe_harbor"].items():
        L.append(f"| {sh} | {', '.join(d['entities']) or '–'} | {', '.join(d['enabled']) or '–'} | {d['status']} |")
    meas = [(e, d["measured_outcomes"]) for e, d in m["entities"].items() if d.get("measured_outcomes")]
    if meas:
        L += ["", "## Measured outcome attribution (run passed with --evidence)", "",
              "Outcomes are type-agnostic: a gold mention counts as protected when any accepted evidence covers it.", "",
              "| entity | dataset | rule | registry | ML | multiple | partial | below thr. | no candidate | disabled only | ASR destroyed |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
        for e, per in meas:
            for ds, a in per.items():
                g = lambda k: str(a.get(k, 0))
                L.append(f"| {e} | {ds} | {g('detected_by_rule')} | {g('detected_by_registry')} | {g('detected_by_ml')} | "
                         f"{g('detected_by_multiple_sources')} | {g('partial_span')} | {g('below_threshold')} | "
                         f"{g('no_candidate')} | {g('disabled_only')} | {g('ASR_destroyed')} |")
    return "\n".join(L) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m harness_eval.matrix")
    ap.add_argument("--config", default=None)
    ap.add_argument("--env", default=None)
    ap.add_argument("--evidence", default=None, help="summary.json of an evaluation run (adds measured attribution)")
    a = ap.parse_args(argv)
    cfg = HarnessConfig.load(a.config, env=a.env)
    m = build(cfg, json.loads(Path(a.evidence).read_text()) if a.evidence else None)
    gen = ROOT / "configs" / "phi" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "entity_responsibility.yaml").write_text("# GENERATED by `python -m harness_eval.matrix` - do not edit by hand.\n"
                                                    + yaml.safe_dump(m, sort_keys=False, allow_unicode=True))
    (ROOT / "docs" / "entity_responsibility_matrix.md").write_text(to_markdown(m))
    print("wrote configs/phi/generated/entity_responsibility.yaml and docs/entity_responsibility_matrix.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
